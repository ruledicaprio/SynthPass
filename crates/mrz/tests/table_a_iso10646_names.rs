#[test]
fn table_a_iso10646_names_has_95_entries() {
    assert_eq!(TABLE_A_ISO10646_NAMES.len(), 95);
}

#[test]
fn table_a_matches_its_iso10646_names() {
    // `mrz::transliterations` is the only public window onto `TABLE_A`'s
    // keys: non-empty exactly where a code point is one of its 95 rows.
    // Scanning past U+1E9E (TABLE_A's highest key, LATIN CAPITAL LETTER
    // SHARP S) with headroom finds every row without ever reading
    // `translit.rs` itself.
    let live_table_a: Vec<char> = ('\u{0000}'..='\u{2000}')
        .filter(|&c| !mrz::transliterations(c).is_empty())
        .collect();

    let mut named: Vec<char> = TABLE_A_ISO10646_NAMES.iter().map(|&(cp, _)| cp).collect();
    named.sort_unstable();
    named.dedup();
    assert_eq!(
        named.len(),
        TABLE_A_ISO10646_NAMES.len(),
        "TABLE_A_ISO10646_NAMES has a duplicate code point"
    );

    assert_eq!(
        live_table_a, named,
        "TABLE_A's live code points differ from the independently-named list: \
         a row's code point was likely swapped for a similar-looking one"
    );
}

/// Table A's five rows whose official name carries no `A`-`Z` base letter to
/// read off. Doc 9303 Part 3 section 6, Table A gives each one's
/// transliteration outright.
const NO_BASE_LETTER: &[(&str, &str)] = &[
    ("LATIN CAPITAL LETTER ETH", "D"),
    ("LATIN CAPITAL LETTER THORN", "TH"),
    ("LATIN SMALL LETTER DOTLESS I", "I"),
    ("LATIN CAPITAL LETTER ENG", "N"),
    ("LATIN CAPITAL LETTER SHARP S", "SS"),
];

/// The letters every transliteration of a row must begin with, read off its
/// official name alone: `B` for `LATIN CAPITAL LETTER B WITH ...`, `AE` for
/// `LATIN CAPITAL LETTER AE`, `IJ` for `LATIN CAPITAL LIGATURE IJ`, or the
/// fixed value in `NO_BASE_LETTER`. `None` for a name none of these covers.
fn implied_prefix(name: &str) -> Option<&str> {
    if let Some(&(_, fixed)) = NO_BASE_LETTER.iter().find(|&&(n, _)| n == name) {
        return Some(fixed);
    }
    let rest = name
        .strip_prefix("LATIN CAPITAL LETTER ")
        .or_else(|| name.strip_prefix("LATIN CAPITAL LIGATURE "))?;
    let base = rest.split(" WITH ").next()?;
    let is_letters = !base.is_empty() && base.chars().all(|c| c.is_ascii_uppercase());
    is_letters.then_some(base)
}

#[test]
fn every_row_transliterates_to_the_letter_its_name_implies() {
    for &(cp, name) in TABLE_A_ISO10646_NAMES {
        let prefix = implied_prefix(name)
            .unwrap_or_else(|| panic!("U+{:04X} {name}: no base letter to read off", cp as u32));
        let variants = mrz::transliterations(cp);
        assert!(
            !variants.is_empty(),
            "U+{:04X} {name} is not a Table A row",
            cp as u32
        );
        for variant in variants {
            assert!(
                variant.starts_with(prefix),
                "U+{:04X} {name}: transliteration {variant:?} does not begin with {prefix:?}",
                cp as u32
            );
        }
    }
}

#[test]
fn gap_characters_pass_through_unchanged() {
    // A sample of `knowledge/docs9303/TABLE_A_LATIN_WITH_COVERAGE.md`'s
    // "Gaps" section -- `LATIN ... WITH ...` characters with no `TABLE_A`
    // row, whose upper-case form is *also* not a `TABLE_A` row (so the
    // case-folding `transliterate` does before lookup can't find a hit
    // either). Doc 9303 recommends no transliteration for any of these;
    // `transliterate` must not drop them.
    let cases: &[(&str, &str)] = &[
        // U+01FA LATIN CAPITAL LETTER A WITH RING ABOVE AND ACUTE: already
        // upper-case, and not a TABLE_A row -- passes through as itself.
        ("\u{01FA}", "\u{01FA}"),
        // U+01FB LATIN SMALL LETTER A WITH RING ABOVE AND ACUTE upper-cases
        // to U+01FA, which is the gap above, not a TABLE_A row.
        ("\u{01FB}", "\u{01FA}"),
        // U+1E00 LATIN CAPITAL LETTER A WITH RING BELOW: already
        // upper-case, not a TABLE_A row.
        ("\u{1E00}", "\u{1E00}"),
        // U+1E03 LATIN SMALL LETTER B WITH DOT ABOVE upper-cases to U+1E02
        // (LATIN CAPITAL LETTER B WITH DOT ABOVE), not a TABLE_A row.
        ("\u{1E03}", "\u{1E02}"),
        // U+0180 LATIN SMALL LETTER B WITH STROKE upper-cases to U+0243
        // (LATIN CAPITAL LETTER B WITH STROKE), not a TABLE_A row.
        ("\u{0180}", "\u{0243}"),
    ];
    for (input, expected) in cases {
        for style in [
            mrz::TransliterationStyle::Expanded,
            mrz::TransliterationStyle::Simple,
            mrz::TransliterationStyle::XxSuffix,
        ] {
            assert_eq!(
                mrz::transliterate(input, style),
                *expected,
                "input {input:?} under {style:?}"
            );
        }
    }
}
