//! #477: an offline, deterministic audit of `translit.rs`'s `TABLE_A` against
//! the ISO 10646 character-name list.
//!
//! ICAO Doc 9303 Part 3 section 6, Table A ("Transliteration of Multinational
//! Latin-based Characters") assigns each of its 95 rows the ISO 10646 name of
//! the code point it prints. The ISO 10646 name list itself is held
//! privately; the Unicode Character Database's `UnicodeData.txt` carries the
//! same names publicly, so `TABLE_A_ISO10646_NAMES` below is checked against
//! it, never against ISO 10646 directly.
//!
//! `TABLE_A_ISO10646_NAMES` was produced independently of `translit.rs`'s own
//! row comments: for each of `TABLE_A`'s 95 code points, its official Unicode
//! name was looked up with Python's standard-library `unicodedata` module
//! (`unicodedata.unidata_version` reported `14.0.0` when this file was
//! written) and copied in below. `table_a_matches_its_iso10646_names` then
//! checks that this independently-derived (code point, name) list names
//! *exactly* the code points `TABLE_A` actually holds -- neither more nor
//! fewer -- which is the mechanical form of "every row is the character it
//! claims to be": a row whose code point had been swapped for a
//! similar-looking one would make this list disagree with `TABLE_A`'s live
//! contents. `every_row_transliterates_to_the_letter_its_name_implies` ties
//! each name to its row's output: every transliteration must begin with the
//! base letter the name reads (`B` for `LATIN CAPITAL LETTER B WITH ...`), so
//! the names are checked against the table, not just carried beside it.
//!
//! This crate stays zero-dependency, so no Unicode name database ships with
//! it or with this test -- the lookup above was performed once, offline, and
//! its result is inlined as plain string literals; `mrz::transliterations`
//! is the only crate API this file calls.
//!
//! The companion gap table for every `LATIN (CAPITAL|SMALL) LETTER ... WITH
//! ...` character `TABLE_A` does *not* cover lives at
//! `knowledge/docs9303/TABLE_A_LATIN_WITH_COVERAGE.md`, generated by
//! `tools/latin_letter_with_coverage.py`. `gap_characters_pass_through_unchanged`
//! below confirms, for a sample of that table's gaps, the behaviour it
//! documents in prose: `mrz::transliterate` never drops a character outside
//! `TABLE_A` -- it passes it through unchanged (upper-cased).

